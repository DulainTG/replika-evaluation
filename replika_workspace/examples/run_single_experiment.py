"""
Example: Running a single experiment (EXP2 - Anisotropic Dispersion Analysis).

This script demonstrates how to programmatically set up and run a specific experiment
outside of the main CLI entrypoint. It covers loading a previously generated 
trajectory dataset and running the analysis.
"""

import os
import sys
from pathlib import Path
import logging

# Add project root to path so we can import src
sys.path.append(str(Path(__file__).parent.parent))

from src.experiments.config.parameters import PhysicsConfig
from src.experiments.exp2_anisotropic_dispersion_analysis import AnisotropicDispersionExperiment
from src.io.persistence import TrajectoryHDF5Store

# Configure logging
logging.basicConfig(level=logging.INFO, format='%(levelname)s: %(message)s')
logger = logging.getLogger(__name__)

def run_example():
    # 1. Setup paths
    # We assume trajectories were already generated by EXP1 or we have some data.
    # For this example, we'll look for them in the default output directory.
    raw_data_dir = Path(os.environ.get("RAW_DATA_DIR", "/raw_data"))
    output_base_dir = Path("./example_outputs")
    output_base_dir.mkdir(parents=True, exist_ok=True)
    
    exp2_out_dir = output_base_dir / "exp2"
    exp2_out_dir.mkdir(parents=True, exist_ok=True)

    # 2. Configuration
    # We use a standard physics configuration.
    config = PhysicsConfig(n_tracers=100) # Use 100 tracers for a quick run
    
    # 3. Ensure we have the trajectory dataset (DS2) and VTK snapshots (DS1)
    # For EXP2, we need both in the same directory because of how it's implemented.
    # In a real scenario, you'd make sure these are available. 
    # Here we'll create a work directory and link/copy what's needed.
    work_dir = exp2_out_dir / "data"
    work_dir.mkdir(parents=True, exist_ok=True)
    
    # Find trajectories.h5 from a previous run or EXP1
    # For demonstration, we'll try to find it in ./outputs/exp1/trajectories.h5
    ds2_source = Path("./outputs/exp1/trajectories.h5")
    if not ds2_source.exists():
        logger.error(f"Trajectory dataset not found at {ds2_source}. Please run EXP1 first.")
        logger.info("Try running: python main.py EXP1 --mode smoke")
        return

    import shutil
    shutil.copy(ds2_source, work_dir / "trajectories.h5")
    
    # Link some VTK files
    vtk_files = sorted(list(raw_data_dir.glob("*.vtk")))[:10] # just some snapshots
    for vtk in vtk_files:
        dest = work_dir / vtk.name
        if not dest.exists():
            os.symlink(vtk, dest)

    # 4. Initialize and Execute the Experiment
    logger.info("Initializing EXP2: Anisotropic Dispersion Analysis...")
    experiment = AnisotropicDispersionExperiment(
        config=config,
        data_dir=work_dir,
        output_dir=exp2_out_dir
    )
    
    logger.info("Executing experiment...")
    result = experiment.execute()
    
    # 5. Review Results
    if result.success:
        logger.info("Experiment completed successfully!")
        logger.info(f"Metrics: {result.metrics}")
        for name, path in result.artifacts.items():
            logger.info(f"Artifact: {name} saved at {path}")
    else:
        logger.error(f"Experiment failed: {result.errors}")

if __name__ == "__main__":
    run_example()
